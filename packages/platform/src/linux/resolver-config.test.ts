import * as fs from 'node:fs/promises';
import * as os from 'node:os';
import * as path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { ResolverConfigurator, parseNameservers, type CommandRunner } from './resolver-config.js';

let root: string;
let stateDir: string;
let backup: string;
let calls: string[];
let resolvedActive: boolean;
let restartFails: boolean;

const runner: CommandRunner = {
  run: async (cmd, args) => {
    calls.push(`${cmd} ${args.join(' ')}`);
    if (args.includes('is-active')) return { code: resolvedActive ? 0 : 3, stdout: '', stderr: '' };
    if (args.includes('restart') && restartFails) return { code: 1, stdout: '', stderr: 'boom' };
    return { code: 0, stdout: '', stderr: '' };
  },
};

const p = (...s: string[]) => path.join(root, ...s);
const RESOLV =
  '# generated by NetworkManager\nsearch home.lan\nnameserver 192.168.1.1\nnameserver 8.8.8.8\noptions edns0\n';

async function write(file: string, text: string, mode = 0o644) {
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, text, { mode });
  await fs.chmod(file, mode);
}
const read = (file: string) => fs.readFile(file, 'utf8');
const exists = (file: string) =>
  fs.lstat(file).then(
    () => true,
    () => false,
  );

const make = (over: Partial<ConstructorParameters<typeof ResolverConfigurator>[0]> = {}) =>
  new ResolverConfigurator({
    root,
    dryRun: false,
    backupPath: backup,
    listen: { address: '127.0.0.1', port: 53 },
    runner,
    ...over,
  });

beforeEach(async () => {
  root = await fs.mkdtemp(path.join(os.tmpdir(), 'hk-res-'));
  stateDir = await fs.mkdtemp(path.join(os.tmpdir(), 'hk-resstate-'));
  backup = path.join(stateDir, 'dns-backup.json');
  calls = [];
  resolvedActive = false;
  restartFails = false;
});
afterEach(async () => {
  await fs.rm(root, { recursive: true, force: true });
  await fs.rm(stateDir, { recursive: true, force: true });
});

describe('parseNameservers', () => {
  it('keeps real servers, drops loopback, wildcard and duplicates, ignores comments and other lines', () => {
    const text =
      '# nameserver 9.9.9.9\nnameserver 127.0.0.53\nnameserver 1.1.1.1\nnameserver 1.1.1.1\n  nameserver   2606:4700::1111\nnameserver ::1\nnameserver 0.0.0.0\nsearch x\nnameserver fe80::1%eth0\n';
    expect(parseNameservers(text)).toEqual(['1.1.1.1', '2606:4700::1111', 'fe80::1%eth0']);
    expect(parseNameservers('')).toEqual([]);
  });
});

describe('strategy and upstreams', () => {
  it('uses systemd-resolved when it is running, resolv.conf when it is not', async () => {
    resolvedActive = true;
    expect(await make().detect()).toBe('systemd-resolved');
    resolvedActive = false;
    expect(await make().detect()).toBe('resolv.conf');
  });

  it('can be forced', async () => {
    resolvedActive = true;
    expect(await make({ strategy: 'resolv.conf' }).detect()).toBe('resolv.conf');
  });

  it('reads upstreams from the real resolver list of systemd-resolved, never the stub', async () => {
    resolvedActive = true;
    await write(
      p('run/systemd/resolve/resolv.conf'),
      'nameserver 192.168.1.1\nnameserver 127.0.0.53\n',
    );
    await write(p('etc/resolv.conf'), 'nameserver 127.0.0.53\n');
    expect(await make().upstreams()).toEqual(['192.168.1.1']);
  });

  it('reads upstreams from resolv.conf, and keeps them after we rewrote it', async () => {
    await write(p('etc/resolv.conf'), RESOLV);
    const c = make();
    expect(await c.upstreams()).toEqual(['192.168.1.1', '8.8.8.8']);
    await c.configure();
    expect(await c.upstreams()).toEqual(['192.168.1.1', '8.8.8.8']);
  });
});

describe('with systemd-resolved', () => {
  beforeEach(async () => {
    resolvedActive = true;
    await write(p('run/systemd/resolve/resolv.conf'), 'nameserver 192.168.1.1\n');
  });
  const dropIn = () => p('etc/systemd/resolved.conf.d/hourkeep.conf');

  it('writes a drop-in pointing at the daemon and restarts resolved', async () => {
    const r = await make().configure();
    expect(r).toEqual({ strategy: 'systemd-resolved', changed: true });
    const text = await read(dropIn());
    expect(text).toContain('[Resolve]\nDNS=127.0.0.1\nDomains=~.\n');
    expect(text).toContain('Managed by hourkeepd');
    expect(calls).toContain('systemctl restart systemd-resolved');
  });

  it('includes the port when it is not 53', async () => {
    await make({ listen: { address: '127.0.0.1', port: 5353 } }).configure();
    expect(await read(dropIn())).toContain('DNS=127.0.0.1:5353\n');
  });

  it('does nothing the second time', async () => {
    const c = make();
    await c.configure();
    calls = [];
    expect(await c.configure()).toMatchObject({ changed: false });
    expect(calls.filter((x) => x.includes('restart'))).toEqual([]);
  });

  it('notices when the drop-in is removed or edited, and repairs it', async () => {
    const c = make();
    await c.configure();
    expect(await c.verify()).toEqual({ ok: true });
    await fs.rm(dropIn());
    expect(await c.verify()).toMatchObject({
      ok: false,
      problem: expect.stringContaining('missing'),
    });
    await c.configure();
    await write(dropIn(), '[Resolve]\nDNS=1.1.1.1\n');
    expect(await c.verify()).toMatchObject({
      ok: false,
      problem: expect.stringContaining('changed'),
    });
    await c.configure();
    expect(await c.verify()).toEqual({ ok: true });
  });

  it('removes the drop-in and restarts resolved on restore, leaving no trace', async () => {
    const c = make();
    await c.configure();
    calls = [];
    expect(await c.restore()).toEqual({ restored: true });
    expect(await exists(dropIn())).toBe(false);
    expect(await exists(backup)).toBe(false);
    expect(calls).toContain('systemctl restart systemd-resolved');
  });

  it('puts back a drop-in that was already there', async () => {
    await write(dropIn(), '[Resolve]\nDNSSEC=yes\n', 0o640);
    const c = make();
    await c.configure();
    expect(await read(dropIn())).toContain('Domains=~.');
    await c.restore();
    expect(await read(dropIn())).toBe('[Resolve]\nDNSSEC=yes\n');
    expect((await fs.stat(dropIn())).mode & 0o777).toBe(0o640);
  });

  it('restores from the saved record alone, as `hourkeepd --teardown` does', async () => {
    await make().configure();
    expect(await make().restore()).toEqual({ restored: true });
    expect(await exists(dropIn())).toBe(false);
  });

  it('still removes a drop-in it left behind if the record is gone', async () => {
    await make().configure();
    await fs.rm(backup);
    expect(await make({ strategy: 'systemd-resolved' }).restore()).toEqual({ restored: true });
    expect(await exists(dropIn())).toBe(false);
  });

  it('leaves a foreign file with the same name alone when there is no record', async () => {
    await write(dropIn(), '[Resolve]\nDNSSEC=yes\n');
    expect(await make().restore()).toEqual({ restored: false });
    expect(await read(dropIn())).toBe('[Resolve]\nDNSSEC=yes\n');
  });

  it('reports a failed restart', async () => {
    restartFails = true;
    await expect(make().configure()).rejects.toThrow(/could not restart systemd-resolved: boom/);
  });

  it('refuses to take over without an upstream, and changes nothing', async () => {
    await write(p('run/systemd/resolve/resolv.conf'), 'nameserver 127.0.0.53\n');
    await expect(make().configure()).rejects.toThrow(/no usable upstream/);
    expect(await exists(dropIn())).toBe(false);
    expect(await exists(backup)).toBe(false);
  });

  it('a dry run reports the change but writes nothing and runs nothing', async () => {
    const r = await make({ dryRun: true }).configure();
    expect(r).toEqual({ strategy: 'systemd-resolved', changed: true });
    expect(await exists(dropIn())).toBe(false);
    expect(await exists(backup)).toBe(false);
    expect(calls.filter((c) => c.includes('restart'))).toEqual([]);
  });
});

describe('with a plain resolv.conf', () => {
  beforeEach(async () => {
    await write(p('etc/resolv.conf'), RESOLV, 0o644);
  });
  const rc = () => p('etc/resolv.conf');

  it('puts our server first and keeps every original line as a fallback', async () => {
    await make().configure();
    const text = await read(rc());
    expect(text.split('\n').filter((l) => l.startsWith('nameserver'))).toEqual([
      'nameserver 127.0.0.1',
      'nameserver 192.168.1.1',
      'nameserver 8.8.8.8',
    ]);
    expect(text).toContain('search home.lan');
    expect(text).toContain('options edns0');
    expect(text).toContain('# generated by NetworkManager');
    expect(text.startsWith('# Managed by hourkeepd')).toBe(true);
  });

  it('restores the exact original bytes and mode', async () => {
    await fs.chmod(rc(), 0o640);
    const c = make();
    await c.configure();
    await c.restore();
    expect(await read(rc())).toBe(RESOLV);
    expect((await fs.stat(rc())).mode & 0o777).toBe(0o640);
    expect(await exists(backup)).toBe(false);
  });

  it('does not run systemctl restart for resolv.conf', async () => {
    const c = make();
    await c.configure();
    await c.restore();
    expect(calls.filter((x) => x.includes('restart'))).toEqual([]);
  });

  it('repairs a rewrite (NetworkManager on reconnect) without losing the original', async () => {
    const c = make();
    await c.configure();
    await write(rc(), 'nameserver 10.0.0.1\n');
    expect(await c.verify()).toMatchObject({
      ok: false,
      problem: expect.stringContaining('no longer points'),
    });
    await c.configure();
    expect(await c.verify()).toEqual({ ok: true });
    await c.restore();
    expect(await read(rc())).toBe(RESOLV); // the backup was never overwritten with our own file
  });

  it('is idempotent and does not stack our line', async () => {
    const c = make();
    await c.configure();
    const once = await read(rc());
    expect(await c.configure()).toMatchObject({ changed: false });
    expect(await read(rc())).toBe(once);
  });

  it('brings back a symlink that was replaced', async () => {
    await fs.rm(rc());
    await write(p('run/systemd/resolve/stub-resolv.conf'), 'nameserver 192.168.1.1\n');
    await fs.symlink('../run/systemd/resolve/stub-resolv.conf', rc());
    const c = make({ strategy: 'resolv.conf' });
    await c.configure();
    expect((await fs.lstat(rc())).isSymbolicLink()).toBe(false);
    await c.restore();
    expect((await fs.lstat(rc())).isSymbolicLink()).toBe(true);
    expect(await fs.readlink(rc())).toBe('../run/systemd/resolve/stub-resolv.conf');
  });

  it('refuses to take over when there is no resolv.conf at all', async () => {
    await fs.rm(rc());
    await expect(make().configure()).rejects.toThrow(/no usable upstream/);
  });

  it('needs port 53, since resolv.conf cannot name a port', async () => {
    await expect(
      make({ listen: { address: '127.0.0.1', port: 5353 } }).configure(),
    ).rejects.toThrow(/port 53/);
    expect(await read(rc())).toBe(RESOLV);
  });

  it('refuses without a real upstream and leaves the file alone', async () => {
    await write(rc(), 'nameserver 127.0.0.53\n');
    await expect(make().configure()).rejects.toThrow(/no usable upstream/);
    expect(await read(rc())).toBe('nameserver 127.0.0.53\n');
    expect(await exists(backup)).toBe(false);
  });

  it('a dry run writes nothing', async () => {
    expect(await make({ dryRun: true }).configure()).toEqual({
      strategy: 'resolv.conf',
      changed: true,
    });
    expect(await read(rc())).toBe(RESOLV);
    expect(await exists(backup)).toBe(false);
  });

  it('keeps the saved record private', async () => {
    await make().configure();
    expect((await fs.stat(backup)).mode & 0o777).toBe(0o600);
  });

  it('restore without any record is a no-op', async () => {
    expect(await make().restore()).toEqual({ restored: false });
    expect(await read(rc())).toBe(RESOLV);
  });
});
